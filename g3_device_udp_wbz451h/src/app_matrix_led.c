#define APP_MATRIX_LED_SwitchOffPanel() { PANEL_OE_Set(); app_matrix_ledData.panelLEDon = false ; }

int row_refresh = 0;

void APP_MATRIX_LED_RefreshPanel(uint8_t *panel)
{
    int row, col;
    
    row = row_refresh++;
    if(row_refresh == PIXEL_ROWS/2)
        row_refresh= 0;
    
    panel = panel + row*PIXEL_COLUMNS;

    for(col=0; col<(PIXEL_COLUMNS); col++)
            {
        if (*panel)         R1_Set();
        else                R1_Clear();
        if (*(panel+1024))  R2_Set();
        else                R2_Clear();

        //Clock
            CLK_Set();
        CLK_Clear();
    
        panel++;
}

    // Set Line Address                
    PANEL_OE_Set();
    
    if (row&0x01) A_Set();
    else        A_Clear();

    if (row&0x02) B_Set();
    else        B_Clear();
    
    if (row&0x04) C_Set();
    else        C_Clear();

    if (row&0x08) D_Set();
    else        D_Clear();

    // Latch
    LAT_Set();
    LAT_Clear();
    PANEL_OE_Clear();
}

void _APP_MATRIX_LED_RefreshTimer(uintptr_t context_)
{
    if(app_matrix_ledData.refreshScreen)
        APP_MATRIX_LED_RefreshPanel(app_matrix_ledData.panel);
}
    
void _APP_MATRIX_LED_TimeExpired(uintptr_t context_refresh)
    {
    app_matrix_ledData.refreshScreen = false;
    }

void APP_MATRIX_LED_InitializePanel(void)
{
    // Clk
    CLK_Clear();
    PANEL_CLK_OutputEnable();
    
    // Latch
    LAT_Clear();
    PANEL_LAT_OutputEnable();
    
    // Addressing
    A_Clear();
    PANEL_A_OutputEnable();
    B_Clear();
    PANEL_B_OutputEnable();
    C_Clear();
    PANEL_C_OutputEnable();
    D_Clear();
    PANEL_D_OutputEnable();
    
    // RGB
    R1_Clear();
    PANEL_R1_OutputEnable();
    R2_Clear();
    PANEL_R2_OutputEnable();
    G1_Clear();
    //PANEL_G1_OutputEnable();
    G2_Clear();
    //PANEL_G2_OutputEnable();
    B1_Clear();
    //PANEL_B1_OutputEnable();
    B2_Clear();
    //PANEL_B2_OutputEnable();
    
    // Output Enable
    OE_Set();
    PANEL_OE_OutputEnable();
        
    APP_MATRIX_LED_SwitchOffPanel();
}

void APP_MATRIX_LED_Initialize ( void )
{   
    // Initialize Panel Led
    APP_MATRIX_LED_InitializePanel();
    
    app_matrix_ledData.timerRefresh_handler = SYS_TIME_HANDLE_INVALID;
    app_matrix_ledData.timerIcon_handler = SYS_TIME_HANDLE_INVALID;
            
    app_matrix_ledData.state = APP_MATRIX_LED_STATE_INIT;
    
    app_matrix_ledData.screenIndex = 0; 
    app_matrix_ledData.refreshScreen = false;
    app_matrix_ledData.panel = &image_data_Microchip_64_32_0;
}

void APP_MATRIX_LED_ShowIcon(uint8_t index)
{
    app_matrix_ledData.screenIndex=index;
    app_matrix_ledData.refreshScreen=true;

    if(app_matrix_ledData.timerIcon_handler != SYS_TIME_HANDLE_INVALID)
    {
        SYS_TIME_TimerDestroy(app_matrix_ledData.timerIcon_handler);
        app_matrix_ledData.timerIcon_handler = SYS_TIME_CallbackRegisterMS(_APP_MATRIX_LED_TimeExpired,
                (uintptr_t) &app_matrix_ledData.context, 5000, SYS_TIME_SINGLE);
    }
}

